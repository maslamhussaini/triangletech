/**
 * Shared translation dictionaries for the tools in localization scope.
 *
 * English is the source of truth and the fallback for every missing key:
 * a missing translation never renders an empty label or a key name.
 * Calculations never read these strings.
 *
 * Coverage is measured by `coverage()` and reported in
 * docs/tools-localization-inventory.md — never mark a tool complete
 * when its keys are missing in a language.
 */
import { DEFAULT_LOCALE, type Locale } from "./locales";

export type PluralForms = { one?: string; other: string; few?: string; many?: string; zero?: string };
export type DictValue = string | PluralForms;
export type Dictionary = Record<string, DictValue>;

function isPlural(value: DictValue): value is PluralForms {
  return typeof value === "object";
}

export function translate(locale: Locale, dict: Dictionary, fallback: Dictionary, key: string, vars?: Record<string, string | number>, count?: number): string {
  const raw = dict[key] ?? fallback[key];
  if (raw === undefined) return key;
  let text: string;
  if (isPlural(raw)) {
    if (count === undefined) {
      text = raw.other;
    } else {
      try {
        const category = new Intl.PluralRules(locale).select(count);
        text = raw[category as keyof PluralForms] ?? raw.other;
      } catch {
        text = count === 1 ? (raw.one ?? raw.other) : raw.other;
      }
    }
  } else {
    text = raw;
  }
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function dictionaryCoverage(dict: Dictionary, fallback: Dictionary): { total: number; present: number; missing: string[] } {
  const keys = Object.keys(fallback);
  const missing = keys.filter(k => !(k in dict));
  return { total: keys.length, present: keys.length - missing.length, missing };
}

